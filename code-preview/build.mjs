// npm ci && npm run build. Output is checked in; Gradle never invokes Node/npm.
import { build } from 'esbuild'
import { mkdir, readFile, writeFile, readdir, rm } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

const root = fileURLToPath(new URL('.', import.meta.url))
const assets = resolve(root, '../app/app/src/main/assets/code-preview')
await mkdir(assets, { recursive: true })
// Only this generator owns this asset directory; discard obsolete hashed chunks.
for (const name of await readdir(assets)) await rm(resolve(assets, name), { recursive: true })
const bundle = await build({
  absWorkingDir: root, entryPoints: ['src/preview.ts'], outdir: assets,
  entryNames: 'preview', chunkNames: 'grammar-[hash]', bundle: true, splitting: true,
  format: 'esm', platform: 'browser', target: 'chrome109', minify: true,
  legalComments: 'eof', sourcemap: false, metafile: true,
})
await writeFile(resolve(assets, 'preview.css'),
  await readFile(resolve(root, 'vendor/shiki.css'), 'utf8') + '\n' +
  await readFile(resolve(root, 'src/preview.css'), 'utf8'))
await writeFile(resolve(assets, 'index.html'), await readFile(resolve(root, 'src/index.html')))
await writeFile(resolve(assets, 'bridge.js'), await readFile(resolve(root, 'src/bridge.js')))
await writeFile(resolve(assets, 'LICENSE'), await readFile(resolve(root, 'vendor/LICENSE')))
// Ship the licenses of every bundled npm package, not just the upstream adaptation.
const packageDirectories = new Set(Object.keys(bundle.metafile.inputs)
  .filter(name => name.startsWith('node_modules/'))
  .map(name => name.split('/').slice(0, name.startsWith('node_modules/@') ? 3 : 2).join('/')))
const notices = []
for (const directory of [...packageDirectories].sort()) {
  const absolute = resolve(root, directory)
  const info = JSON.parse(await readFile(resolve(absolute, 'package.json'), 'utf8'))
  const licenses = (await readdir(absolute)).filter(name => /^licen[cs]e(?:[.-]|$)/i.test(name))
  if (licenses.length === 0) throw new Error(`Missing bundled license: ${info.name}`)
  for (const license of licenses) notices.push(`${info.name}@${info.version}\n${await readFile(resolve(absolute, license), 'utf8')}`)
}
await writeFile(resolve(assets, 'THIRD_PARTY_NOTICES'), notices.join('\n\n---\n\n'))
// Generate the native extension lookup from the exact same vendored table as JS.
const languageModule = await build({
  absWorkingDir: root, entryPoints: ['vendor/code-language.ts'], bundle: true,
  format: 'esm', platform: 'node', write: false,
})
const language = await import('data:text/javascript;base64,' + Buffer.from(languageModule.outputFiles[0].text).toString('base64'))
const groups = new Map()
for (const extension of language.CODE_HIGHLIGHT_EXTENSIONS) {
  const id = language.languageForPath('file.' + extension)
  if (!groups.has(id)) groups.set(id, [])
  groups.get(id).push(extension)
}
const cases = [...groups].map(([id, extensions]) =>
  '    ' + extensions.map(extension => JSON.stringify(extension)).join(', ') + ' -> ' + JSON.stringify(id))
await writeFile(resolve(root, '../app/app/src/main/kotlin/dev/dsh/pocket/app/CodePreviewLanguages.kt'),
  '// Generated by code-preview/build.mjs from DeepSeek MIT code-language; do not edit.\n' +
  'package dev.dsh.pocket.app\n\n' +
  'internal fun previewCodeLanguage(path: String): String? {\n' +
  '    val base = path.substringAfterLast(\'/\').substringAfterLast(\'\\\\\')\n' +
  '    if (!base.contains(\'.\')) return null\n' +
  '    return when (base.substringAfterLast(\'.\').lowercase(java.util.Locale.ROOT)) {\n' +
  cases.map(line => '    ' + line).join('\n') + '\n        else -> null\n    }\n}\n')
// The exact whitelist is consumed by the WebView interceptor, never a directory prefix.
const names = (await readdir(assets)).filter(name => /\.(?:js|css|html)$/.test(name)).sort()
await writeFile(resolve(assets, 'manifest.json'), JSON.stringify(names) + '\n')
